defmodule AgentProof.AI.Demo do
  @moduledoc """
  AI provider that builds evidence from the case facts, without a language model.
  """

  @behaviour AgentProof.AI.Provider

  @impl true
  def name, do: "demo"

  # Words that describe a purchase rather than name the product.
  @filler ~w(buy purchase get order find a an the some new good nice cheap best great quality)

  @impl true
  def generate(%{task: :search_query, facts: %{"description" => description}}, _opts) do
    {:ok, %{"product" => search_query(description), "details" => []}}
  end

  def generate(%{facts: facts}, _opts) do
    {:ok,
     %{
       "summary" => summary(facts),
       "authorization_evidence" => authorization_evidence(facts),
       "transaction_evidence" => transaction_evidence(facts),
       "fulfillment_evidence" => fulfillment_evidence(facts),
       "ai_explanation" =>
         "Generated by AgentProof's deterministic demo provider from stored records. " <>
           "No language model was used."
     }}
  end

  defp summary(%{
         "agent_name" => agent,
         "authorization" => authorization,
         "transaction" => transaction,
         "dispute" => dispute,
         "checks" => checks
       }) do
    budget = if checks["within_budget"], do: "within", else: "outside"

    "The customer disputed this purchase as #{String.replace(dispute["reason"], "_", " ")}. " <>
      "#{agent} bought #{transaction["product_name"]} for #{transaction["amount"]} " <>
      "#{transaction["currency"]}, #{budget} the #{authorization["max_amount"]} " <>
      "#{authorization["currency"]} budget the customer authorized."
  end

  defp authorization_evidence(%{
         "agent_name" => agent,
         "authorization" => authorization,
         "checks" => checks
       }) do
    %{
      "statement" =>
        "The customer authorized #{agent} to spend up to #{authorization["max_amount"]} " <>
          ~s(#{authorization["currency"]}: "#{authorization["description"]}".),
      "facts" =>
        [
          "Authorization recorded at #{authorization["authorized_at"]}.",
          budget_fact(checks),
          currency_fact(checks)
        ] ++ edited_facts(authorization)
    }
  end

  defp edited_facts(%{"edited_after_purchase" => true}),
    do: [
      "The authorization was edited after this purchase; the terms above are those in force when it was made."
    ]

  defp edited_facts(_authorization), do: []

  defp budget_fact(%{"within_budget" => true, "system_budget_check_logged" => true}),
    do: "AgentProof's own budget check approved the amount before payment."

  defp budget_fact(%{"within_budget" => true}),
    do: "The amount is within the authorized budget."

  defp budget_fact(_checks), do: "The amount exceeds the authorized budget."

  defp currency_fact(%{"currency_matches" => true}),
    do: "The purchase currency matches the authorization."

  defp currency_fact(_checks), do: "The purchase currency does not match the authorization."

  defp transaction_evidence(%{"transaction" => transaction, "agent_actions" => actions}) do
    %{
      "statement" =>
        "PayPal order #{transaction["paypal_order_id"]} was placed for " <>
          "#{transaction["amount"]} #{transaction["currency"]} " <>
          "(#{transaction["product_name"]}).",
      "facts" =>
        Enum.map(actions, &"#{&1["at"]}: #{&1["actor"]} performed #{&1["action"]}.") ++
          capture_facts(transaction)
    }
  end

  defp capture_facts(%{"capture_simulated" => true}),
    do: ["The payment capture was simulated; no real funds moved."]

  defp capture_facts(_transaction), do: []

  defp fulfillment_evidence(%{"fulfillment" => nil}) do
    %{"statement" => "No fulfillment record exists for this transaction.", "facts" => []}
  end

  defp fulfillment_evidence(%{"fulfillment" => fulfillment, "checks" => checks}) do
    %{
      "statement" =>
        "#{fulfillment["carrier"]} delivered the order " <>
          "(tracking #{fulfillment["tracking_number"]}) at #{fulfillment["delivered_at"]}.",
      "facts" => [delivery_timing(checks)]
    }
  end

  defp delivery_timing(%{"delivered_before_dispute" => true}),
    do: "Delivery happened before the dispute was opened."

  defp delivery_timing(_checks), do: "Delivery happened after the dispute was opened."

  # The product phrase ends before words like "for" or "up to", and its last word
  # usually names the product: "noise-cancelling headphones" -> "headphones".
  defp search_query(description) do
    description
    |> String.downcase()
    |> String.split(~r/[,(]|\b(for|up to|under|below|with|that)\b/u, parts: 2)
    |> hd()
    |> String.split(~r/[^\p{L}\p{N}-]+/u, trim: true)
    |> Enum.reject(&(&1 in @filler or &1 =~ ~r/^\d+$/))
    |> List.last("")
  end
end
